console.log("Hello World");

let a = 4;
console.log(a);

// Check the data type
console.log(typeof a);

// String
let c = "Abhishek Kumar";
console.log(c);

// Boolean
let d = true;
console.log(d);

// Null
let e = null;
console.log(e);
console.log(typeof e); // "object" (this is a known JavaScript quirk)

// Undefined
let f;
console.log(f);
console.log(typeof f); // "undefined"

// If you want to change c, don't use var
c = "Abis";
console.log(c);